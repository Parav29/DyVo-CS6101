def read(p, default="(missing)"):
    p = Path(p)
    return p.read_text().rstrip() if p.exists() else default


def timing(name):
    t = {}
    for line in read(ROOT / "logs" / f"{name}.timing", "").splitlines():
        key, _, val = line.partition(" ")
        t[key] = val
    if "start" in t and "end" in t:
        end, _, rc = t["end"].partition(" exit ")
        secs = (datetime.fromisoformat(end) - datetime.fromisoformat(t["start"])).total_seconds()
        t["wall"] = f"{secs / 3600:.2f} h"
        t["exit"] = rc
    return t


def result(name):
    files = sorted(glob.glob(str(ROOT / "DyVo" / "outputs" / name / "*" / "test_result.json")))
    return (json.load(open(files[-1])), files[-1]) if files else (None, None)


def health(name):
    """Scan the train log for the logged dicts: entity counts, NaN losses, last step."""
    log = ROOT / "logs" / f"{name}.log"
    if not log.exists():
        return None
    rows, nan, steps = [], False, []
    for line in log.read_text(errors="replace").splitlines():
        for m in re.finditer(r"\{'query reg'[^}]*\}", line):
            try:
                d = ast.literal_eval(m.group(0).replace("nan", "None"))
            except (ValueError, SyntaxError):
                continue
            rows.append(d)
            nan |= d.get("loss_no_reg") is None or (isinstance(d.get("loss_no_reg"), float) and math.isnan(d["loss_no_reg"]))
        steps += [int(s) for s in re.findall(r"(\d+)/100000 \[", line)]
    return {"logged": len(rows), "nan": nan, "first": rows[0] if rows else None, "last": rows[-1] if rows else None,
            "min_q_ent": min((r.get("query #entities", 0) for r in rows), default=None),
            "min_d_ent": min((r.get("doc #entities", 0) for r in rows), default=None),
            "step": max(steps, default=0), "oom": "CUDA out of memory" in log.read_text(errors="replace")}


